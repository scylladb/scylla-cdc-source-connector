"""Check prepared release identity, token migration and GitHub asset boundaries."""

from contextlib import contextmanager
import json
import os
from pathlib import Path
import subprocess
import sys
import tempfile
import unittest
from unittest.mock import patch
import xml.etree.ElementTree as ET

import assets
import signing

ROOT = Path(__file__).resolve().parents[2]


class AssetTests(unittest.TestCase):
    @contextmanager
    def repository(self, source_pom=None):
        original = Path.cwd()
        with tempfile.TemporaryDirectory() as directory:
            os.chdir(directory)
            try:
                def git(*args):
                    subprocess.run(["git", "-c", "user.name=Test", "-c",
                                    "user.email=test@example.invalid", "-c", "commit.gpgsign=false",
                                    "-c", "tag.gpgSign=false", *args],
                                   check=True, capture_output=True)
                git("init", "--quiet")
                pom = ET.fromstring(source_pom if source_pom is not None else (ROOT / "pom.xml").read_text())
                pom.find("{http://maven.apache.org/POM/4.0.0}version").text = "2.0.8"
                Path("pom.xml").write_bytes(ET.tostring(pom))
                git("add", "pom.xml")
                git("commit", "--quiet", "-m", "Release")
                git("tag", "v2.0.8")
                git("tag", "v99.99.99")
                Path("release.properties").write_text(
                    "# Generated by Maven\nscm.tag=v2.0.8\n"
                    "project.rel.com.scylladb\\:scylla-cdc-source-connector=2.0.8\n")
                yield
            finally:
                os.chdir(original)

    def test_prepared_metadata_selects_identity_and_assets_despite_other_tags(self):
        with self.repository():
            self.assertEqual(assets.identity(), ("v2.0.8", "2.0.8"))
            self.assertEqual([str(path) for path in assets.artifacts()], [
                "target/checkout/target/fat-jar/scylla-cdc-source-connector-2.0.8-jar-with-dependencies.jar",
                "target/checkout/target/components/packages/scylladb-scylla-cdc-source-connector-2.0.8.zip"])

    def test_fixture_identity_is_independent_of_source_version(self):
        source = ET.parse(ROOT / "pom.xml").getroot()
        source.find("{http://maven.apache.org/POM/4.0.0}version").text = "91.7.4-SNAPSHOT"
        with self.repository(ET.tostring(source)):
            self.assertEqual(assets.identity(), ("v2.0.8", "2.0.8"))

    def test_identity_survives_successful_maven_perform_cleanup(self):
        with self.repository():
            signing.PREPARED_METADATA.parent.mkdir(parents=True)
            signing.PREPARED_METADATA.write_bytes(Path("release.properties").read_bytes())
            Path("release.properties").unlink()
            self.assertEqual(assets.identity(), ("v2.0.8", "2.0.8"))

    def test_malformed_duplicate_and_inconsistent_metadata_fails(self):
        with self.repository():
            original = Path("release.properties").read_text()
            for text in (original + "scm.tag=v2.0.8\n", original.replace("v2.0.8", "v2.0.8-invalid"),
                         original.replace("=2.0.8", "=2.0.9"),
                         original.replace("v2.0.8", "v99.99.99"),
                         original.replace("scm.tag=v2.0.8", "scm.tag=../unsafe")):
                Path("release.properties").write_text(text)
                with self.subTest(text=text), self.assertRaises(signing.SigningError):
                    assets.identity()

    def test_missing_and_placeholder_tokens_fail_without_printing_values(self):
        for user, password in (("", "real-password"), ("real-user", ""),
                               ("PLACEHOLDER_NOT_CONFIGURED", "real-password"),
                               ("real-user", "PLACEHOLDER_NOT_CONFIGURED")):
            with patch.dict(os.environ, {"SONATYPE_TOKEN_USERNAME": user,
                                         "SONATYPE_TOKEN_PASSWORD": password}, clear=True):
                with self.assertRaises(signing.SigningError) as error:
                    assets.check_tokens()
                self.assertNotIn("real-", str(error.exception))
        with patch.dict(os.environ, {"SONATYPE_TOKEN_USERNAME": "real-user",
                                     "SONATYPE_TOKEN_PASSWORD": "real-password"}, clear=True):
            assets.check_tokens()

    @contextmanager
    def publication(self, mode="new"):
        with self.repository():
            root = Path.cwd()
            state, trace = root / "github-state.json", root / "github-trace.jsonl"
            state.write_text(json.dumps({"mode": mode, "draft": mode == "existing_draft",
                                         "published": mode == "existing_published",
                                         "assets": ["retained-existing-asset"] if mode.startswith("existing_") else []}))
            files = assets.artifacts()
            for path in files:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_bytes(b"test-artifact")
                Path(str(path) + ".asc").write_bytes(b"test-signature")
            gh = root / "gh"
            gh.write_text(
                f"#!{sys.executable}\n"
                "import json,os,sys\nfrom pathlib import Path\n"
                "path=Path(os.environ['FAKE_GH_STATE'])\nstate=json.loads(path.read_text())\n"
                "args=sys.argv[1:]\n"
                "with Path(os.environ['FAKE_GH_TRACE']).open('a') as log:\n"
                " log.write(json.dumps({'operation':'lookup' if args[:2]==['api','graphql'] else args[1],'args':args})+'\\n')\n"
                "if args[:2]==['api','graphql']:\n"
                " assert 'tag=v2.0.8' in args and 'owner={owner}' in args and 'name={repo}' in args\n"
                " if state['mode']=='lookup_failure': raise SystemExit(19)\n"
                " if state['mode']=='malformed_lookup': print('{invalid'); raise SystemExit(0)\n"
                " repository={'release':{'id':'existing-id'} if state['draft'] or state['published'] else None}\n"
                " result={'data':{'repository':None if state['mode']=='null_repository' else repository}}\n"
                " if state['mode']=='lookup_graphql_error': result['errors']=[{'message':'lookup failed'}]\n"
                " print(json.dumps(result)); raise SystemExit(0)\n"
                "if args[:2]==['release','create']:\n"
                " assert not state['draft'] and not state['published']\n"
                " assert all(flag in args for flag in ['--verify-tag','--draft','--generate-notes'])\n"
                " files=args[3:args.index('--verify-tag')]\n"
                " assert len(files)==4 and all(Path(name).is_file() for name in files)\n"
                " assert state['verified']==files[::2]\n"
                " if state['mode']=='create_failure': raise SystemExit(17)\n"
                " state.update(draft=True,assets=files[:1] if state['mode']=='upload_failure' else files)\n"
                " path.write_text(json.dumps(state))\n"
                " raise SystemExit(18 if state['mode']=='upload_failure' else 0)\n"
                "if args==['release','edit','v2.0.8','--draft=false']:\n"
                " assert state['draft'] and len(state['assets'])==4\n"
                " state.update(draft=False,published=True)\n path.write_text(json.dumps(state))\n"
                " raise SystemExit(0)\nraise SystemExit(99)\n"
            )
            gh.chmod(0o700)

            def verify(selected):
                with trace.open("a") as log:
                    log.write(json.dumps({"operation": "verify", "files": list(map(str, selected))}) + "\n")
                if mode == "bad_signature":
                    raise signing.SigningError("Bad signature")
                current = json.loads(state.read_text())
                current["verified"] = list(map(str, selected))
                state.write_text(json.dumps(current))

            with patch.object(assets.signing, "sign_files", side_effect=verify), patch.dict(
                os.environ, {"PATH": str(root) + os.pathsep + os.environ["PATH"],
                             "FAKE_GH_STATE": str(state), "FAKE_GH_TRACE": str(trace)}
            ):
                yield state, trace, files

    def operations(self, trace):
        return [json.loads(line)["operation"] for line in trace.read_text().splitlines()] if trace.exists() else []

    def test_publish_verifies_signatures_before_contacting_github(self):
        with self.publication("bad_signature") as (state, trace, _):
            with self.assertRaisesRegex(signing.SigningError, "Bad signature"):
                assets.publish()
            self.assertEqual(self.operations(trace), ["verify"])
            self.assertFalse(json.loads(state.read_text())["published"])
        with self.publication() as (_, trace, files):
            Path(str(files[0]) + ".asc").unlink()
            with self.assertRaisesRegex(signing.SigningError, "Sign and verify"):
                assets.publish()
            self.assertEqual(self.operations(trace), [])

    def test_publish_refuses_existing_release_or_draft(self):
        for mode in ("existing_published", "existing_draft"):
            with self.subTest(mode=mode), self.publication(mode) as (state, trace, _):
                original = json.loads(state.read_text())
                with self.assertRaisesRegex(signing.SigningError, "release or draft already exists"):
                    assets.publish()
                self.assertEqual(self.operations(trace), ["verify", "lookup"])
                current = json.loads(state.read_text())
                for key in ("draft", "published", "assets"):
                    self.assertEqual(current[key], original[key])

    def test_publish_stages_all_four_assets_before_publishing(self):
        with self.publication() as (state, trace, files):
            with patch.object(subprocess, "run", wraps=subprocess.run) as invoke:
                assets.publish()
            self.assertEqual([(call.args[0][:3], call.kwargs["timeout"])
                              for call in invoke.call_args_list if call.args[0][0] == "gh"], [
                (["gh", "api", "graphql"], 60),
                (["gh", "release", "create"], 1800),
                (["gh", "release", "edit"], 1800)])
            self.assertEqual(self.operations(trace), ["verify", "lookup", "create", "edit"])
            current = json.loads(state.read_text())
            self.assertEqual(current["assets"], [str(item) for path in files for item in (path, str(path) + ".asc")])
            self.assertTrue(current["published"])
            self.assertFalse(current["draft"])

    def test_failed_creation_or_upload_never_publishes(self):
        for mode in ("create_failure", "upload_failure"):
            with self.subTest(mode=mode), self.publication(mode) as (state, trace, _):
                with self.assertRaises(signing.SigningError):
                    assets.publish()
                self.assertEqual(self.operations(trace), ["verify", "lookup", "create"])
                current = json.loads(state.read_text())
                self.assertFalse(current["published"])
                self.assertEqual(current["draft"], mode == "upload_failure")
                self.assertEqual(len(current["assets"]), 1 if mode == "upload_failure" else 0)

    def test_discovery_errors_are_not_absence(self):
        for mode in ("lookup_failure", "malformed_lookup", "null_repository", "lookup_graphql_error"):
            with self.subTest(mode=mode), self.publication(mode) as (state, trace, _):
                with self.assertRaisesRegex(signing.SigningError, "Could not inspect GitHub release"):
                    assets.publish()
                self.assertEqual(self.operations(trace), ["verify", "lookup"])
                current = json.loads(state.read_text())
                self.assertFalse(current["draft"])
                self.assertFalse(current["published"])
                self.assertEqual(current["assets"], [])


if __name__ == "__main__":
    unittest.main()
